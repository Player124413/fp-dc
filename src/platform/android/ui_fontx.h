/* Ё: Е under two dots, which costs the row the Е would use for its top bar */
static const unsigned char ui_font_yo[UI_FONT_H] = { 0x15, 0x1f, 0x10, 0x1e, 0x10, 0x10, 0x1f };

/* next codepoint of a UTF-8 string; a broken byte reads as '?' and never stops the walk */
static inline int ui_utf8_next(const char **pp) {
    const unsigned char *p = (const unsigned char *)*pp;
    if (!p || !*p) return 0;
    if (p[0] < 0x80) { *pp = (const char *)(p + 1); return p[0]; }
    if ((p[0] & 0xe0) == 0xc0 && (p[1] & 0xc0) == 0x80) {
        *pp = (const char *)(p + 2);
        return ((p[0] & 0x1f) << 6) | (p[1] & 0x3f);
    }
    if ((p[0] & 0xf0) == 0xe0 && (p[1] & 0xc0) == 0x80 && (p[2] & 0xc0) == 0x80) {
        *pp = (const char *)(p + 3);
        return ((p[0] & 0x0f) << 12) | ((p[1] & 0x3f) << 6) | (p[2] & 0x3f);
    }
    *pp = (const char *)(p + 1);
    return '?';
}

/* the seven rows of a codepoint, or NULL when the font has no glyph for it */
static inline const unsigned char *ui_glyph_rows(int cp) {
    if (cp >= 'a' && cp <= 'z') cp -= 32;
    if (cp >= UI_FONT_FIRST && cp <= UI_FONT_LAST) return ui_font_rows[cp - UI_FONT_FIRST];
    if (cp >= 0x430 && cp <= 0x44f) cp -= 0x20;               /* lower case: the capitals */
    if (cp >= UI_FONT_RU_FIRST && cp <= UI_FONT_RU_LAST) return ui_font_ru[cp - UI_FONT_RU_FIRST];
    if (cp == 0x401 || cp == 0x451) return ui_font_yo;
    return NULL;
}

/* how many characters a string has (not how many bytes) */
static inline int ui_text_chars(const char *s) {
    int n = 0;
    if (!s) return 0;
    while (*s) { ui_utf8_next(&s); n++; }
    return n;
}

